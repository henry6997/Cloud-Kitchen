/** Regenerates supabase/seed.sql from the same sample menu the demo mode uses. Run: pnpm --filter @blip/db gen:seed */
import { createHash } from "node:crypto";
import { writeFileSync } from "node:fs";
import { seedCatalog } from "../src/server/seed";

const uuid = (key: string): string => {
  const h = createHash("md5").update(`blip:${key}`).digest("hex");
  return `${h.slice(0, 8)}-${h.slice(8, 12)}-4${h.slice(13, 16)}-a${h.slice(17, 20)}-${h.slice(20, 32)}`;
};
const q = (s: string | null): string => (s === null ? "null" : `'${s.replace(/'/g, "''")}'`);
const b = (v: boolean): string => (v ? "true" : "false");

const { categories, products, banners, settings } = seedCatalog();
const out: string[] = ["-- Sample menu for Blip. Generated by packages/db/scripts/gen-seed-sql.ts; safe to re-run.", "begin;", ""];

out.push("insert into public.settings (id, kitchen_name, address, phone, delivery_fee_paise, free_delivery_threshold_paise, min_order_paise, gst_percent, delivery_pincodes, pickup_eta_minutes, delivery_eta_text, enforce_kitchen_hours) values");
out.push(`  (true, ${q(settings.kitchenName)}, ${q(settings.address)}, ${q(settings.phone)}, ${settings.deliveryFeePaise}, ${settings.freeDeliveryThresholdPaise}, ${settings.minOrderPaise}, ${settings.gstPercent}, array[${settings.deliveryPincodes.map((p) => q(p)).join(", ")}], ${settings.pickupEtaMinutes}, ${q(settings.deliveryEtaText)}, ${b(settings.enforceKitchenHours)})`);
out.push("on conflict (id) do nothing;", "");

out.push("insert into public.categories (id, name, emoji, image_url, sort_order, is_visible) values");
out.push(categories.map((c) => `  ('${uuid(c.id)}', ${q(c.name)}, ${q(c.emoji)}, ${q(c.imageUrl)}, ${c.sortOrder}, ${b(c.isVisible)})`).join(",\n"));
out.push("on conflict (id) do nothing;", "");

out.push("insert into public.products (id, category_id, name, description, price_paise, compare_price_paise, image_url, emoji, is_veg, is_available, is_popular, is_combo, tag, prep_minutes, rating, rating_count, sort_order) values");
out.push(products.map((p) => `  ('${uuid(p.id)}', '${uuid(p.categoryId)}', ${q(p.name)}, ${q(p.description)}, ${p.pricePaise}, ${p.comparePricePaise ?? "null"}, ${q(p.imageUrl)}, ${q(p.emoji)}, ${b(p.isVeg)}, ${b(p.isAvailable)}, ${b(p.isPopular)}, ${b(p.isCombo)}, ${q(p.tag)}, ${p.prepMinutes}, ${p.rating}, ${p.ratingCount}, ${p.sortOrder})`).join(",\n"));
out.push("on conflict (id) do nothing;", "");

const groups = products.flatMap((p) => p.optionGroups.map((g, i) => ({ g, i })));
out.push("insert into public.option_groups (id, product_id, name, kind, is_required, sort_order) values");
out.push(groups.map(({ g, i }) => `  ('${uuid(g.id)}', '${uuid(g.productId)}', ${q(g.name)}, '${g.kind}', ${b(g.isRequired)}, ${i})`).join(",\n"));
out.push("on conflict (id) do nothing;", "");

out.push("insert into public.options (id, group_id, name, price_delta_paise, is_available, sort_order) values");
out.push(groups.flatMap(({ g }) => g.options.map((o, i) => `  ('${uuid(o.id)}', '${uuid(g.id)}', ${q(o.name)}, ${o.priceDeltaPaise}, ${b(o.isAvailable)}, ${i})`)).join(",\n"));
out.push("on conflict (id) do nothing;", "");

out.push("insert into public.banners (id, image_url, label, link_type, link_target, slot, sort_order, is_active) values");
out.push(banners.map((x) => `  ('${uuid(x.id)}', ${q(x.imageUrl)}, ${q(x.label)}, '${x.linkType}', ${q(x.linkTarget)}, '${x.slot}', ${x.sortOrder}, ${b(x.isActive)})`).join(",\n"));
out.push("on conflict (id) do nothing;", "", "commit;", "");

writeFileSync(new URL("../../../supabase/seed.sql", import.meta.url), out.join("\n"));
console.log("wrote supabase/seed.sql");
